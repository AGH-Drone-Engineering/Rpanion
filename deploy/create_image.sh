#!/bin/bash

## Create a disk image of the Pi's SD card
## This should be run on a host computer with
## the Pi's SD card inserted
set -e
set -x

#TIMESTAMP="$(date -u '+%Y%m%d%H%M%S')"
FILENAME="Rpanion-Server-X.Y.Z-RasPiOS.img"
DEVICE=/dev/mmcblk0
time (sudo dd status=progress if=$DEVICE of=$FILENAME status=progress) # ~1G/minute

## Remove per-device identity from the image. An empty /etc/machine-id gets a
## new random ID on boot. It is not a first boot for systemd ("uninitialized"
## would be, and would apply unit presets, re-enabling dnsmasq.service and
## ssh.socket), so SSH host keys are regenerated by the ssh.service drop-in
## from deploy/configure_system.sh. Without the drop-in the keys are kept.
MNT=$(mktemp -d)
LOOP=$(sudo losetup --find --show --partscan "$FILENAME")
cleanup() {
    sudo umount "$MNT" 2>/dev/null || true
    sudo losetup -d "$LOOP" 2>/dev/null || true
    rmdir "$MNT" 2>/dev/null || true
}
trap cleanup EXIT
sudo mount "${LOOP}p2" "$MNT"
if [ -f "$MNT/etc/systemd/system/ssh.service.d/rpanion-hostkeys.conf" ]; then
    sudo rm -f "$MNT"/etc/ssh/ssh_host_*_key*
else
    echo "WARNING: ssh.service drop-in missing in the image, SSH host keys kept (shared by all cards)." >&2
    echo "         Run deploy/configure_system.sh on the source card to fix." >&2
fi
sudo truncate -s 0 "$MNT/etc/machine-id"
sudo rm -f "$MNT/var/lib/dbus/machine-id"
cleanup
trap - EXIT

sudo ./pishrink.sh -Zpa $FILENAME # from https://github.com/Drewsif/PiShrink
